type Index = HashMap<String, Vec<(String, String)>>;

fn ord(lang: Lang) -> usize {
    match lang {
        Lang::Deu => 0,
        Lang::Ces => 1,
        Lang::Dan => 2,
        Lang::Eng => 3,
        Lang::Est => 4,
        Lang::Fin => 5,
        Lang::Fra => 6,
        Lang::Slv => 7,
        Lang::Spa => 8,
        Lang::Por => 9,
        Lang::Gle => 10,
        Lang::Ita => 11,
        Lang::Ron => 12,
        Lang::Swe => 13,
        Lang::Cat => 14,
        Lang::Ukr => 15,
        Lang::Isl => 16,
    }
}

fn index(lang: Lang) -> &'static Index {
    #[allow(clippy::declare_interior_mutable_const)]
    const EMPTY: OnceLock<Index> = OnceLock::new();
    static INDEXES: [OnceLock<Index>; 17] = [EMPTY; 17];
    INDEXES[ord(lang)].get_or_init(|| build_index(lang))
}

fn build_index(lang: Lang) -> Index {
    let mut idx: Index = HashMap::new();
    for lemma in lexicon_lemmas(lang) {
        let Some(forms) = forms_for(lemma, lang) else {
            continue;
        };
        let mut infinitive = lemma.to_string();
        for (form, slot) in &forms {
            if slot == "infinitive" {
                infinitive.clone_from(form);
            }
        }
        for (form, slot) in forms {
            let entry = idx.entry(form.to_lowercase()).or_default();
            let pair = (infinitive.clone(), slot);
            if !entry.contains(&pair) {
                entry.push(pair);
            }
        }
    }
    idx
}

fn is_lexicon_lemma(cand: &str, lang: Lang) -> bool {
    #[allow(clippy::declare_interior_mutable_const)]
    const EMPTY: OnceLock<std::collections::HashSet<&'static str>> = OnceLock::new();
    static SETS: [OnceLock<std::collections::HashSet<&'static str>>; 17] = [EMPTY; 17];
    SETS[ord(lang)]
        .get_or_init(|| lexicon_lemmas(lang).into_iter().collect())
        .contains(cand)
}

