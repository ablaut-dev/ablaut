const P6: [&str; 6] = ["1sg", "2sg", "3sg", "1pl", "2pl", "3pl"];
const P9: [&str; 9] = [
    "1sg", "2sg", "3sg", "1du", "2du", "3du", "1pl", "2pl", "3pl",
];
const P7: [&str; 7] = ["1sg", "2sg", "3sg", "1pl", "2pl", "3pl", "autonomous"];

struct Slots(Vec<(String, String)>);

impl Slots {
    fn one(&mut self, form: &str, name: &str) {
        if !form.is_empty()
            && form != "-"
            && form != "\u{2014}"
            && !form.contains(char::is_whitespace)
        {
            self.0.push((form.to_string(), name.to_string()));
        }
    }
    fn opt(&mut self, form: Option<&String>, name: &str) {
        if let Some(f) = form {
            self.one(f, name);
        }
    }
    fn row(&mut self, forms: &[String], tense: &str, labels: &[&str]) {
        for (f, l) in forms.iter().zip(labels) {
            self.one(f, &format!("{tense} {l}"));
        }
    }
    fn row_opt(&mut self, forms: &[Option<String>], tense: &str, labels: &[&str]) {
        for (f, l) in forms.iter().zip(labels) {
            self.opt(f.as_ref(), &format!("{tense} {l}"));
        }
    }
}

