/// Every single-word form of a lemma with its slot descriptor. For
/// most languages this is the `Table`; French and Spanish also emit
/// spelling variants (payer's *paye*, the Spanish -se subjunctive,
/// the 1990 French grave-accent future), and Irish emits the bare
/// analytic bases (chuaigh) that the display table only shows glued
/// to a pronoun.
fn forms_for(lemma: &str, lang: Lang) -> Option<Vec<(String, String)>> {
    match lang {
        Lang::Fra => fra_forms(lemma),
        Lang::Spa => spa_forms(lemma),
        Lang::Gle => gle_forms(lemma),
        Lang::Deu => deu_forms(lemma),
        _ => conjugate(lemma, lang).ok().map(|t| enumerate(&t)),
    }
}

/// German forms, with the clause-final spelling of separable verbs
/// joined back on: the table renders "dankten ab", but in subordinate
/// clauses the same slot is written *abdankten*, and that is the form
/// corpora index. Two-word forms whose second word is the verb's own
/// leading particle are re-joined; live recombination of free-standing
/// "fängt ... an" word pairs stays out of scope.
fn deu_forms(lemma: &str) -> Option<Vec<(String, String)>> {
    let table = conjugate(lemma, Lang::Deu).ok()?;
    let Conjugation::Deu(t) = &table else {
        unreachable!()
    };
    let infinitive = t.infinitive.clone();
    let mut forms = enumerate(&table);
    let mut joined: Vec<(String, String)> = Vec::new();
    let mut join = |row: &[String], tense: &str, labels: &[&str]| {
        for (f, l) in row.iter().zip(labels) {
            if let Some((verb, particle)) = f.split_once(' ') {
                if !particle.contains(' ') && infinitive.starts_with(particle) {
                    joined.push((
                        format!("{particle}{verb}"),
                        format!("{tense} {l} (clause-final)"),
                    ));
                }
            }
        }
    };
    join(&t.present, "present", &P6);
    join(&t.preterite, "preterite", &P6);
    join(&t.konjunktiv1, "konjunktiv i", &P6);
    join(&t.konjunktiv2, "konjunktiv ii", &P6);
    forms.append(&mut joined);
    Some(forms)
}

fn fra_forms(lemma: &str) -> Option<Vec<(String, String)>> {
    use crate::fra::{Number, Person, SimpleTense, Verb};
    let v = Verb::from_infinitive(lemma).ok()?;
    let mut s = Slots(Vec::new());
    s.one(&v.infinitive(), "infinitive");
    for f in v.present_participle_variants() {
        s.one(&f, "present participle");
    }
    // The agreeing participle forms (allée, vendus, mises): fem +e,
    // pl +s (masc pl unchanged after -s/-x).
    let pp = v.past_participle();
    s.one(&pp, "past participle");
    if !pp.ends_with('s') && !pp.ends_with('x') {
        s.one(&format!("{pp}s"), "past participle masc pl");
    }
    s.one(&format!("{pp}e"), "past participle fem sg");
    s.one(&format!("{pp}es"), "past participle fem pl");
    let persons = [
        (Person::First, Number::Singular, "1sg"),
        (Person::Second, Number::Singular, "2sg"),
        (Person::Third, Number::Singular, "3sg"),
        (Person::First, Number::Plural, "1pl"),
        (Person::Second, Number::Plural, "2pl"),
        (Person::Third, Number::Plural, "3pl"),
    ];
    for (p, n, l) in [
        (Person::Second, Number::Singular, "2sg"),
        (Person::First, Number::Plural, "1pl"),
        (Person::Second, Number::Plural, "2pl"),
    ] {
        for f in v.imperative_variants(p, n) {
            s.one(&f, &format!("imperative {l}"));
        }
    }
    for (t, name) in [
        (SimpleTense::Present, "present"),
        (SimpleTense::Imperfect, "imperfect"),
        (SimpleTense::PastHistoric, "past historic"),
        (SimpleTense::Future, "future"),
        (SimpleTense::Conditional, "conditional"),
        (SimpleTense::SubjunctivePresent, "subjunctive present"),
        (SimpleTense::SubjunctiveImperfect, "subjunctive imperfect"),
    ] {
        for (p, n, l) in persons {
            for f in v.variants(t, p, n) {
                s.one(&f, &format!("{name} {l}"));
            }
        }
    }
    Some(s.0)
}

fn spa_forms(lemma: &str) -> Option<Vec<(String, String)>> {
    use crate::spa::{Number, Person, SimpleTense, Verb};
    let v = Verb::from_infinitive(lemma).ok()?;
    let mut s = Slots(Vec::new());
    s.one(&v.infinitive(), "infinitive");
    s.one(&v.gerund(), "gerund");
    for (fem, pl, l) in [
        (false, false, "masc sg"),
        (true, false, "fem sg"),
        (false, true, "masc pl"),
        (true, true, "fem pl"),
    ] {
        s.one(
            &v.past_participle_inflected(fem, pl),
            &format!("past participle {l}"),
        );
    }
    let persons = [
        (Person::First, Number::Singular, "1sg"),
        (Person::Second, Number::Singular, "2sg"),
        (Person::Third, Number::Singular, "3sg"),
        (Person::First, Number::Plural, "1pl"),
        (Person::Second, Number::Plural, "2pl"),
        (Person::Third, Number::Plural, "3pl"),
    ];
    for (p, n, l) in [
        (Person::Second, Number::Singular, "tú"),
        (Person::Third, Number::Singular, "usted"),
        (Person::First, Number::Plural, "nosotros"),
        (Person::Second, Number::Plural, "vosotros"),
        (Person::Third, Number::Plural, "ustedes"),
    ] {
        if let Some(f) = v.imperative(p, n) {
            s.one(&f, &format!("imperative {l}"));
        }
    }
    for (t, name) in [
        (SimpleTense::Present, "present"),
        (SimpleTense::Imperfect, "imperfect"),
        (SimpleTense::Preterite, "preterite"),
        (SimpleTense::Future, "future"),
        (SimpleTense::Conditional, "conditional"),
        (SimpleTense::SubjunctivePresent, "subjunctive present"),
        (SimpleTense::SubjunctiveImperfect, "subjunctive imperfect"),
        (SimpleTense::SubjunctiveFuture, "subjunctive future"),
    ] {
        for (p, n, l) in persons {
            for f in v.variants(t, p, n) {
                s.one(&f, &format!("{name} {l}"));
            }
        }
    }
    Some(s.0)
}

fn gle_forms(lemma: &str) -> Option<Vec<(String, String)>> {
    use crate::gle::{Slot, Tense, Verb};
    let v = Verb::from_infinitive(lemma).ok()?;
    let mut s = Slots(Vec::new());
    s.one(v.infinitive(), "infinitive");
    s.one(&v.verbal_noun(), "verbal noun");
    s.one(&v.verbal_adjective(), "verbal adjective");
    for (t, name) in [
        (Tense::Present, "present"),
        (Tense::Past, "past"),
        (Tense::PastHabitual, "past habitual"),
        (Tense::Future, "future"),
        (Tense::Conditional, "conditional"),
        (Tense::Imperative, "imperative"),
        (Tense::Subjunctive, "subjunctive"),
    ] {
        // The written standard lenites past/habitual/conditional forms
        // (téigh → chuaigh); the autonomous is lenited only in the
        // habitual and conditional. Mirrors gle::Table::row.
        let mutate = matches!(t, Tense::Past | Tense::PastHabitual | Tense::Conditional);
        let mutate_auto = matches!(t, Tense::PastHabitual | Tense::Conditional);
        for (slot, l) in [
            (Slot::Base, ""),
            (Slot::FirstSingular, " 1sg"),
            (Slot::SecondSingular, " 2sg"),
            (Slot::FirstPlural, " 1pl"),
            (Slot::SecondPlural, " 2pl"),
            (Slot::ThirdPlural, " 3pl"),
            (Slot::Autonomous, " autonomous"),
        ] {
            if let Some(f) = v.form(t, slot) {
                let f = if (mutate && slot != Slot::Autonomous)
                    || (mutate_auto && slot == Slot::Autonomous)
                {
                    Verb::lenite(&f)
                } else {
                    f
                };
                s.one(&f, &format!("{name}{l}"));
            }
        }
    }
    Some(s.0)
}

