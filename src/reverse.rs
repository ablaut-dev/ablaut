//! Reverse lookup: from a conjugated form back to the infinitive(s).
//!
//! Two complementary mechanisms, both built on the forward engine so a
//! returned analysis is always conjugationally consistent:
//!
//! * **Irregular index** (all 14 languages): on first use, every lemma
//!   in the language's compiled-in exception lexicon is forward-
//!   conjugated and every single-word form is indexed as
//!   `form → (infinitive, slot)`. No new data ships — the index is
//!   derived from the TSVs the crate already embeds.
//! * **Productive de-inflection** (deu, eng, fra, spa): candidate
//!   infinitives are generated by re-segmenting the form (all stem
//!   splits × the language's infinitive endings, plus a few
//!   orthographic mutations such as French è→é and consonant
//!   degemination), then each candidate is forward-conjugated and kept
//!   only if the queried form occurs in its table. Verification means
//!   a match can never cite a slot the engine would not itself produce.
//!
//! Two auxiliary mechanisms extend both paths:
//!
//! * **Prefixed recombination**: when a suffix of the query is an
//!   indexed form of a base verb, the remainder glued onto that base's
//!   infinitive becomes a candidate (*abstiendra* → abs+tenir →
//!   abstenir, *widersprach* → wider+sprechen → widersprechen,
//!   *sunrose* → sun+rise), again subject to forward verification.
//! * **Spelling-variant matching** (deu, eng): the engine emits one
//!   canonical spelling, but the written language allows more; a small
//!   rewrite table bridges them (*meid*/meide, *überträfst*/
//!   überträfest, *verringret*/verringert, British *travelling*).
//!
//! When the form is found in the irregular index, the two classic
//! ghost shapes are suppressed: *suis* is être/suivre, not the
//! hypothetical second-group *\*suir*, and *war* is sein, not the
//! weak *\*waren*.
//!
//! Known limitations (v1):
//! * German separable recombination of free word pairs is out of
//!   scope: *fängt an* (two words) does not reverse; the single-word
//!   spellings *anfängt* (clause-final), *angefangen*, and
//!   *anzufangen* all do.
//! * For forms not covered by the index, the productive path can
//!   return hypothetical lemmas alongside the real one whenever the
//!   surface form is genuinely ambiguous under the engine's own rules
//!   (*vendons* → vendre but also the nonce *\*vender*, which the
//!   engine happily conjugates; *appellerons* → appeler and the
//!   -eller reading). The true lemma is always in the set; index
//!   matches sort first, then shorter candidates.
//! * Multi-word forms (analytic tenses, reflexive clitics) are not
//!   indexed and not de-inflected, and Spanish voseo forms are
//!   excluded from matching.
//! * Only variants the forward engine (plus the rewrite tables) can
//!   produce are found: archaic or regional doublets the engine does
//!   not generate (*schwämme* beside schwömme, English *lit* where
//!   the lexicon holds lighted) do not reverse.

use crate::{conjugate, Conjugation, Lang};
use std::collections::HashMap;
use std::sync::OnceLock;

/// One analysis of a queried form: an infinitive whose paradigm
/// contains the form, plus every slot the form occupies in it.
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize))]
pub struct ReverseMatch {
    pub infinitive: String,
    /// Slot descriptors like "present 1sg" or "past participle".
    pub slots: Vec<String>,
}

/// Look up a conjugated form: every infinitive whose paradigm contains
/// it, with the slots it fills. Input is trimmed and case-folded like
/// `from_infinitive`. Ambiguous forms return several matches (French
/// *suis* → être and suivre); unknown forms return an empty vector.
#[must_use]
pub fn reverse(form: &str, lang: Lang) -> Vec<ReverseMatch> {
    let query = form.trim().to_lowercase();
    if query.is_empty() || query.contains(char::is_whitespace) {
        return Vec::new();
    }

    // Irregular index first: authoritative for lexicon verbs. French
    // bound stems (-cevoir, -uire) are index-internal: they anchor
    // prefixed recombination below but are not verbs themselves.
    let mut out: Vec<ReverseMatch> = Vec::new();
    if let Some(hits) = index(lang).get(&query) {
        let mut by_lemma: Vec<(String, Vec<String>)> = Vec::new();
        for (inf, slot) in hits {
            if lang == Lang::Fra && FRA_BOUND_STEMS.contains(&inf.as_str()) {
                continue;
            }
            match by_lemma.iter_mut().find(|(l, _)| l == inf) {
                Some((_, slots)) => {
                    if !slots.contains(slot) {
                        slots.push(slot.clone());
                    }
                }
                None => by_lemma.push((inf.clone(), vec![slot.clone()])),
            }
        }
        by_lemma.sort_by(|a, b| a.0.cmp(&b.0));
        out.extend(
            by_lemma
                .into_iter()
                .map(|(infinitive, slots)| ReverseMatch { infinitive, slots }),
        );
    }
    let indexed_hit = !out.is_empty();

    // Prefixed recombination against the index: if a suffix of the
    // query is a known form of an indexed base verb, the prefix glued
    // onto that base's infinitive is a candidate (abstiendra →
    // abs+tenir, widersprach → wider+sprechen, sunrose → sun+rise).
    // Verification below decides whether the engine really supports
    // the prefixed derivative.
    let mut cands = candidates(&query, lang);
    let spellings = if lang == Lang::Deu {
        deu_spellings(&query)
    } else {
        vec![query.clone()]
    };
    for q in &spellings {
        // An alternate spelling may be a known form outright:
        // söfft is the engine's söffet with the schwa dropped.
        if q != &query {
            if let Some(hits) = index(lang).get(q.as_str()) {
                for (inf, _) in hits {
                    if !cands.contains(inf) {
                        cands.push(inf.clone());
                    }
                }
            }
        }
        for (i, _) in q.char_indices().skip(1) {
            let mut push_hits = |key: &str| {
                if let Some(hits) = index(lang).get(key) {
                    for (inf, _) in hits {
                        let cand = format!("{}{inf}", &q[..i]);
                        if !cands.contains(&cand) {
                            cands.push(cand);
                        }
                    }
                }
            };
            push_hits(&q[i..]);
            if lang == Lang::Deu {
                // Inseparable prefixes swallow the participle ge-:
                // entgangen ends in gangen, indexed as gegangen.
                push_hits(&format!("ge{}", &q[i..]));
            }
        }
    }

    // Productive de-inflection: verified candidates. When the form is
    // already claimed by the irregular index, the classic ghost shapes
    // are suppressed (suis must not surface the second-group *suir,
    // war must not surface the weak *waren); other productive readings
    // coexist with the index (gehört is hören's participle and a form
    // of gehören).
    let mut verified: Vec<ReverseMatch> = Vec::new();
    for cand in cands {
        if out.iter().any(|m| m.infinitive == cand) {
            continue; // already found via the index
        }
        if indexed_hit && is_index_shadow(&cand, &query, lang) {
            continue;
        }
        if let Some(m) = verify(&cand, &query, lang) {
            if !verified.iter().any(|v| v.infinitive == m.infinitive) {
                verified.push(m);
            }
        }
    }
    if lang == Lang::Eng && indexed_hit {
        // "went" is a form of go, not the infinitive of *went.
        verified.retain(|m| m.infinitive != query || m.slots.iter().any(|s| s != "infinitive"));
    }

    // Orthographic-twin filter: drop a verified candidate when a more
    // canonical spelling of it (appeller→appeler, cèder→céder,
    // stoppe→stop, studie→study) is itself verified or indexed.
    let keep: Vec<bool> = verified
        .iter()
        .map(|m| {
            !canonical_twins(&m.infinitive, lang).iter().any(|t| {
                t != &m.infinitive
                    && (verified.iter().any(|v| &v.infinitive == t)
                        || out.iter().any(|v| &v.infinitive == t))
            })
        })
        .collect();
    let mut verified: Vec<ReverseMatch> = verified
        .into_iter()
        .zip(keep)
        .filter_map(|(m, k)| k.then_some(m))
        .collect();

    verified.sort_by(|a, b| {
        a.infinitive
            .chars()
            .count()
            .cmp(&b.infinitive.chars().count())
            .then_with(|| a.infinitive.cmp(&b.infinitive))
    });
    out.extend(verified);
    out
}

/// Whether the forward engine itself generates `form` for `lemma`
/// (modulo the same spelling-variant matching `reverse` uses). Test
/// harness support, not public API.
#[doc(hidden)]
#[must_use]
pub fn engine_generates(lemma: &str, form: &str, lang: Lang) -> bool {
    verify(lemma, &form.trim().to_lowercase(), lang).is_some()
}

/// The productive ghost shapes that shadow every irregular form and
/// are only worth suppressing when the index already explains the
/// query: the French second-group reading (any X-is/X-it form yields
/// a hypothetical X-ir) and the German weak verb built on the query
/// itself as a stem (war → *waren). Lexicon lemmas are never ghosts.
fn is_index_shadow(cand: &str, query: &str, lang: Lang) -> bool {
    if is_lexicon_lemma(cand, lang) {
        return false;
    }
    match lang {
        Lang::Fra => cand.ends_with("ir") || cand.ends_with("re"),
        Lang::Deu => cand
            .strip_suffix('n')
            .is_some_and(|b| b == query || b.strip_suffix('e') == Some(query)),
        _ => false,
    }
}

/// Forward-conjugate `cand` and collect the slots where `query`
/// appears. None when the candidate is not a verb shape the engine
/// accepts, or its paradigm does not contain the query.
fn verify(cand: &str, query: &str, lang: Lang) -> Option<ReverseMatch> {
    let mut slots: Vec<String> = Vec::new();
    let mut infinitive = None;
    for (form, slot) in forms_for(cand, lang)? {
        if slot == "infinitive" {
            infinitive = Some(form.clone());
        }
        let form = form.to_lowercase();
        let hit = form == query
            || (lang == Lang::Deu && deu_variant_match(&form, query))
            || (lang == Lang::Eng && eng_variant_match(&form, query));
        if hit && !slots.contains(&slot) {
            slots.push(slot);
        }
    }
    let infinitive = infinitive?;
    // The engine may normalize the candidate (case, zu-stripping); a
    // candidate that normalizes onto a different lemma already in the
    // set would duplicate it, which the caller dedupes by infinitive.
    (!slots.is_empty()).then_some(ReverseMatch { infinitive, slots })
}

/// German spelling variants the engine does not emit but the written
/// language allows: the optional imperative/1sg schwa (meid/meide,
/// dulde/duld), the epenthetic -e- of 2sg/2pl endings (überträfst/
/// überträfest), and the mobile schwa of -eln/-ern stems (heuchle/
/// heuchele, verringert/verringret). A table form matches a query if
/// one rewrite bridges them.
fn deu_variant_match(form: &str, query: &str) -> bool {
    if let Some(b) = form.strip_suffix('e') {
        if b == query {
            return true;
        }
    }
    if query.strip_suffix('e') == Some(form) {
        return true;
    }
    for (a, b) in DEU_REWRITES {
        if let Some(stem) = form.strip_suffix(a) {
            if query.strip_prefix(stem) == Some(b) {
                return true;
            }
        }
    }
    false
}

/// The British doubled-l spelling (travelling, mislabelled) matched
/// against the engine's single-l American forms. Restricted to -ll-
/// after a longer stem so filled does not match file's *filed.
fn eng_variant_match(form: &str, query: &str) -> bool {
    for suf in ["ing", "ed"] {
        if let Some(qstem) = query.strip_suffix(suf) {
            if qstem.ends_with("ll") && qstem.len() >= 6 {
                if let Some(d) = degeminate(qstem) {
                    if format!("{d}{suf}") == form {
                        return true;
                    }
                }
            }
        }
    }
    false
}

/// The spellings a German query might be written in besides its own:
/// the same rewrites, applied to the query. Used to anchor prefixed
/// recombination (vorzögst → vorzögest, whose -zögest tail the index
/// knows as ziehen).
fn deu_spellings(query: &str) -> Vec<String> {
    let mut v = vec![query.to_string()];
    match query.strip_suffix('e') {
        Some(b) => v.push(b.to_string()),
        None => v.push(format!("{query}e")),
    }
    for (a, b) in DEU_REWRITES {
        if let Some(stem) = query.strip_suffix(a) {
            v.push(format!("{stem}{b}"));
        }
    }
    v
}

