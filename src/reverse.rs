const FR_VOWELS: &str = "aeiouyàâéèêëîïôûü";

/// Candidate infinitives for the productive de-inflection path.
/// Over-generation is fine — every candidate is verified by forward
/// conjugation — so the generators favour recall over precision.
fn candidates(query: &str, lang: Lang) -> Vec<String> {
    let mut set: Vec<String> = Vec::new();
    let mut push = |s: String| {
        if !set.contains(&s) {
            set.push(s);
        }
    };
    let prefixes = |s: &str| -> Vec<String> {
        s.char_indices()
            .skip(1)
            .map(|(i, _)| s[..i].to_string())
            .chain(std::iter::once(s.to_string()))
            .collect()
    };
    match lang {
        Lang::Fra => {
            let mut stems = prefixes(query);
            for stem in prefixes(query) {
                // appell → appel (consonant degemination).
                if let Some(d) = degeminate(&stem) {
                    stems.push(d);
                }
                // lèv → lev / léd → cèd → céd (1990 and classic grave).
                if let Some(i) = stem.rfind('è') {
                    stems.push(format!("{}é{}", &stem[..i], &stem[i + "è".len()..]));
                    stems.push(format!("{}e{}", &stem[..i], &stem[i + "è".len()..]));
                }
                // pai → pay, essui → essuy (y-stem verbs).
                if let Some(base) = stem.strip_suffix('i') {
                    if base.chars().last().is_some_and(|c| FR_VOWELS.contains(c)) {
                        stems.push(format!("{base}y"));
                    }
                }
                // annonç → annonc (cedilla before a/o endings).
                if let Some(base) = stem.strip_suffix('ç') {
                    stems.push(format!("{base}c"));
                }
            }
            for stem in stems {
                for end in ["er", "ir", "re"] {
                    push(format!("{stem}{end}"));
                }
            }
        }
        Lang::Spa => {
            let mut stems = prefixes(query);
            for stem in prefixes(query) {
                // Diphthong and vowel alternations back to the lemma
                // vowel: cuent → cont/cunt, quier → quer, pid → ped.
                for (from, tos) in [("ue", &["o", "u"][..]), ("ie", &["e", "i"]), ("i", &["e"])] {
                    if let Some(i) = stem.rfind(from) {
                        for to in tos {
                            stems.push(format!("{}{to}{}", &stem[..i], &stem[i + from.len()..]));
                        }
                    }
                }
                // Orthographic stem-final alternations: saqu → sac,
                // llegu → lleg, empec → empez, coj → cog, averigü →
                // averigu, conozc → conoc, arguy → argü.
                for (suf, to) in [
                    ("qu", "c"),
                    ("gu", "g"),
                    ("c", "z"),
                    ("j", "g"),
                    ("gü", "gu"),
                    ("zc", "c"),
                    ("uy", "ü"),
                ] {
                    if let Some(base) = stem.strip_suffix(suf) {
                        stems.push(format!("{base}{to}"));
                    }
                }
            }
            for stem in stems {
                for end in ["ar", "er", "ir"] {
                    push(format!("{stem}{end}"));
                }
            }
            // Strong participle families whose stem reshapes the whole
            // ending: abierto→abrir, inscrita→inscribir,
            // devuelto→devolver (with gender/number agreement).
            let bare = query.strip_suffix('s').unwrap_or(query);
            let bare = match bare.strip_suffix('a') {
                Some(b) => format!("{b}o"),
                None => bare.to_string(),
            };
            for (pat, repl) in [("ierto", "rir"), ("crito", "cribir"), ("uelto", "olver")] {
                if let Some(base) = bare.strip_suffix(pat) {
                    push(format!("{base}{repl}"));
                }
            }
        }
        Lang::Deu => {
            // Besides plain re-segmentation, drop a "ge" (participle:
            // gekauft → kauft*, angefangen → anfangen) or a "zu"
            // (anzufangen → anfangen) anywhere in the form.
            let mut bases = vec![query.to_string()];
            for infix in ["ge", "zu"] {
                let mut at = 0;
                while let Some(i) = query[at..].find(infix) {
                    let i = at + i;
                    bases.push(format!("{}{}", &query[..i], &query[i + infix.len()..]));
                    at = i + infix.len();
                }
            }
            for base in bases {
                let mut stems = prefixes(&base);
                // Umlauted present (stößt) and Konjunktiv II (käme)
                // stems back to the lemma vowel.
                for stem in prefixes(&base) {
                    for (from, to) in [("äu", "au"), ("ä", "a"), ("ö", "o"), ("ü", "u")] {
                        if let Some(i) = stem.rfind(from) {
                            stems.push(format!("{}{to}{}", &stem[..i], &stem[i + from.len()..]));
                        }
                    }
                    // Mobile schwa of -eln/-ern verbs: the elided stem
                    // (rumkümml-, verringr-, abmeir-) back to the
                    // lemma shape.
                    if stem.ends_with(['l', 'r']) && stem.chars().count() >= 3 {
                        let cut = stem.len() - 1;
                        stems.push(format!("{}e{}", &stem[..cut], &stem[cut..]));
                    }
                }
                for stem in stems {
                    push(format!("{stem}en"));
                    push(format!("{stem}n"));
                }
            }
        }
        Lang::Eng => {
            let mut stems = prefixes(query);
            for stem in prefixes(query) {
                if let Some(d) = degeminate(&stem) {
                    stems.push(d); // stopp → stop
                }
                if let Some(base) = stem.strip_suffix('i') {
                    stems.push(format!("{base}y")); // tri → try
                }
            }
            for stem in stems {
                push(stem.clone());
                push(format!("{stem}e"));
            }
        }
        _ => {}
    }
    set
}

/// Undouble a stem-final geminate consonant (appell → appel).
fn degeminate(stem: &str) -> Option<String> {
    let mut chars = stem.chars();
    let last = chars.next_back()?;
    let prev = chars.next_back()?;
    (last == prev && last.is_alphabetic() && !"aeiouyàâéèêëîïôûü".contains(last))
        .then(|| stem[..stem.len() - last.len_utf8()].to_string())
}

/// More canonical spellings of a candidate infinitive: if one of these
/// is itself a verified match, the candidate is an orthographic ghost
/// of it (appeller of appeler, cèder of céder, stoppe of stop) and is
/// dropped. Deliberately narrow — real doublets stay untouched.
/// Only French has twins worth filtering. There is deliberately no
/// degemination twin (for "appellerons" both appeler and an -eller
/// reading genuinely exist in French orthography), and English is left
/// unfiltered: for "advised" both advise and the nonce *advis verify,
/// and no orthographic rule can pick one without claiming the other
/// direction for "stopped" (stop vs *stoppe).
fn canonical_twins(cand: &str, lang: Lang) -> Vec<String> {
    let mut twins = Vec::new();
    if lang == Lang::Fra {
        for end in ["er", "ir", "re"] {
            if let Some(stem) = cand.strip_suffix(end) {
                if let Some(base) = stem.strip_suffix('i') {
                    if base.chars().last().is_some_and(|c| FR_VOWELS.contains(c)) {
                        twins.push(format!("{base}y{end}")); // paier → payer
                    }
                }
            }
        }
        if let Some(i) = cand.rfind('è') {
            // cèder → céder / lèver → lever.
            twins.push(format!("{}é{}", &cand[..i], &cand[i + "è".len()..]));
            twins.push(format!("{}e{}", &cand[..i], &cand[i + "è".len()..]));
        }
    }
    twins
}

