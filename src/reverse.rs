/// The lemma column of every lexicon TSV the language module already
/// embeds. These are exactly the verbs with non-productive morphology
/// (plus, for some languages, class or auxiliary listings — harmless
/// extra coverage).
fn lexicon_lemmas(lang: Lang) -> Vec<&'static str> {
    fn col1(tsv: &'static str, out: &mut Vec<&'static str>) {
        for line in tsv.lines() {
            if line.starts_with('#') || line.is_empty() {
                continue;
            }
            let lemma = line.split('\t').next().unwrap_or("").trim();
            if !lemma.is_empty()
                && !lemma.contains(char::is_whitespace)
                && !lemma.contains(['\'', '\u{2019}'])
            {
                out.push(lemma);
            }
        }
    }
    let mut lemmas = Vec::new();
    match lang {
        Lang::Deu => {
            col1(include_str!("../data/deu/verbs.tsv"), &mut lemmas);
            // The stored suppletives live in code, not in the TSV.
            lemmas.extend(["sein", "werden", "tun"]);
        }
        Lang::Ces => {
            col1(include_str!("../data/ces/verbs.tsv"), &mut lemmas);
            col1(include_str!("../data/ces/classes.tsv"), &mut lemmas);
            col1(include_str!("../data/ces/aspect.tsv"), &mut lemmas);
        }
        Lang::Dan => {
            col1(include_str!("../data/dan/parts.tsv"), &mut lemmas);
            col1(include_str!("../data/dan/auxiliaries.tsv"), &mut lemmas);
        }
        Lang::Eng => col1(include_str!("../data/eng/verbs.tsv"), &mut lemmas),
        Lang::Est => col1(include_str!("../data/est/verbs.tsv"), &mut lemmas),
        Lang::Fin => col1(include_str!("../data/fin/verbs.tsv"), &mut lemmas),
        // Bound stems stay in: their indexed forms anchor prefixed
        // recombination (apercevais → aper+cevoir → apercevoir); the
        // direct lookup filters them out of results.
        Lang::Fra => col1(include_str!("../data/fra/verbs.tsv"), &mut lemmas),
        Lang::Slv => {
            col1(include_str!("../data/slv/verbs.tsv"), &mut lemmas);
            col1(include_str!("../data/slv/classes.tsv"), &mut lemmas);
        }
        Lang::Spa => {
            col1(include_str!("../data/spa/verbs.tsv"), &mut lemmas);
            col1(include_str!("../data/spa/classes.tsv"), &mut lemmas);
        }
        Lang::Por => {
            col1(include_str!("../data/por/verbs.tsv"), &mut lemmas);
            col1(include_str!("../data/por/classes.tsv"), &mut lemmas);
        }
        Lang::Gle => col1(include_str!("../data/gle/verbs.tsv"), &mut lemmas),
        Lang::Ita => {
            col1(include_str!("../data/ita/verbs.tsv"), &mut lemmas);
            col1(include_str!("../data/ita/strong.tsv"), &mut lemmas);
            col1(include_str!("../data/ita/classes.tsv"), &mut lemmas);
            col1(include_str!("../data/ita/auxiliaries.tsv"), &mut lemmas);
        }
        Lang::Ron => {
            col1(include_str!("../data/ron/verbs.tsv"), &mut lemmas);
            col1(include_str!("../data/ron/classes.tsv"), &mut lemmas);
        }
        Lang::Swe => col1(include_str!("../data/swe/parts.tsv"), &mut lemmas),
        Lang::Cat => col1(include_str!("../data/cat/verbs.tsv"), &mut lemmas),
        Lang::Ukr => col1(include_str!("../data/ukr/verbs.tsv"), &mut lemmas),
        Lang::Isl => col1(include_str!("../data/isl/verbs.tsv"), &mut lemmas),
    }
    lemmas.sort_unstable();
    lemmas.dedup();
    lemmas
}

